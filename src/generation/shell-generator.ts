// Main Generation Function
// =============================================================================

/**
 * Generates a shell script from a flowsh workflow
 */
export function generateShellScript(
  workflow: FlowshWorkflow,
  options: GenerationOptions = {}
): GenerationResult {
  const { includeMocks = true } = options;

  const warnings: string[] = [];

  // Get workflow graph
  const graph = workflow.graph ?? workflow.spec?.graph;
  if (!graph || !graph.nodes || graph.nodes.length === 0) {
    return {
      script: '',
      success: false,
      warnings: ['No workflow graph found or graph is empty'],
      metadata: {
        nodeCount: 0,
        edgeCount: 0,
        hasAgentNodes: false,
        hasLLMNodes: false,
        estimatedComplexity: 'low',
      },
    };
  }

  // Analyze workflow complexity
  const metadata = analyzeWorkflow(graph.nodes, graph.edges || []);

  // Generate script components
  const scriptParts: string[] = [];

  // 1. Header and setup
  scriptParts.push(generateScriptHeader(workflow, options));

  // 2. Utility functions
  scriptParts.push(generateUtilityFunctions());

  // 3. Mock functions (if enabled)
  if (includeMocks) {
    scriptParts.push(generateMockFunctions());
  }

  // 4. Template system
  scriptParts.push(generateTemplateSystem(workflow));

  // 5. Node execution functions
  scriptParts.push(generateNodeFunctions(graph.nodes));

  // 6. Main execution flow
  scriptParts.push(generateMainFlow(graph.nodes, graph.edges || []));

  // 7. Argument parsing and initialization
  scriptParts.push(generateArgumentParsing(workflow));

  // 8. Script footer
  scriptParts.push(generateScriptFooter());

  const script = scriptParts.join('\n\n');

  return {
    script,
    success: true,
    warnings,
    metadata,
  };
}

