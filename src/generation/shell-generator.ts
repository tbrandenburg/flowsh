/**
 * Analyzes workflow complexity and characteristics
 */
function analyzeWorkflow(
  nodes: WorkflowNode[],
  edges: WorkflowEdge[]
): GenerationResult['metadata'] {
  const nodeCount = nodes.length;
  const edgeCount = edges.length;

  const hasAgentNodes = nodes.some(isAgentNode);
  const hasLLMNodes = nodes.some(isLLMNode);
  const hasLoopNodes = nodes.some(isLoopNode);
  const hasIterationNodes = nodes.some(isIterationNode);
  const hasIfElseNodes = nodes.some(isIfElseNode);

  let estimatedComplexity: 'low' | 'medium' | 'high' = 'low';

  if (nodeCount > 10 || hasLoopNodes || hasIterationNodes) {
    estimatedComplexity = 'high';
  } else if (nodeCount > 5 || hasIfElseNodes || (hasAgentNodes && hasLLMNodes)) {
    estimatedComplexity = 'medium';
  }

  return {
    nodeCount,
    edgeCount,
    hasAgentNodes,
    hasLLMNodes,
    estimatedComplexity,
  };
}
