/**
 * Generates template system functions
 */
function generateTemplateSystem(workflow: FlowshWorkflow): string {
  const dependencies =
    workflow.workflow?.template_dependencies || workflow.spec?.template_dependencies || [];

  let templateCases = '';
  for (const dep of dependencies) {
    templateCases += `        "${dep.template_id}")
            cat <<'TEMPLATE'
# Template: ${dep.template_id}
# Source: ${dep.source}
# Version: ${dep.version || 'latest'}
You are an AI assistant. Please process this request: {{task_description}}

Be helpful, accurate, and concise in your response.
TEMPLATE
            ;;
`;
  }

  return `# =============================================================================
# TEMPLATE SYSTEM
# =============================================================================

# Template resolution with fallback system
resolve_template() {
    local template_id="\$1"
    local source="\${2:-library}"
    
    log_debug "Resolving template: \$template_id from \$source"
    
    case "\$template_id" in
${templateCases}        "task-planner")
            cat <<'TEMPLATE'
You are a task planner. Break down this task: {{task_description}}

Create actionable steps and implement them systematically.
Focus on:
1. Understanding requirements
2. Breaking down into subtasks  
3. Implementation planning
4. Testing strategy

Keep your response concise and actionable.
TEMPLATE
            ;;
        "code-reviewer")
            cat <<'TEMPLATE'
Review and analyze this task: {{task_description}}

Provide feedback on:
1. Code quality and best practices
2. Potential security issues
3. Performance considerations
4. Testing coverage
TEMPLATE
            ;;
        *)
            log_error "Unknown template '\$template_id'"
            return 1
            ;;
    esac
}

# Template rendering with variable substitution
render_template() {
    local template="\$1"
    local task_description="\$2"
    
    # Validate inputs
    [[ -z "\$template" ]] && {
        log_error "Template content is empty"
        return 1
    }
    [[ -z "\$task_description" ]] && {
        log_error "Task description is empty"
        return 1
    }
    
    # Use the variable substitution function
    local rendered_template="\$(substitute_variables "\$template")"
    
    # Handle specific variable substitutions for backward compatibility
    rendered_template=\$(echo "\$rendered_template" | sed "s|{{task_description}}|\$task_description|g")
    
    echo "\$rendered_template"
}`;
}

/**
 * Generates node execution functions
 */
function generateNodeFunctions(nodes: WorkflowNode[]): string {
  const functions: string[] = [];

  functions.push('# =============================================================================');
  functions.push('# NODE EXECUTION FUNCTIONS');
  functions.push('# =============================================================================');

  for (const node of nodes) {
    const functionName = `execute_node_${node.id.replace(/[^a-zA-Z0-9]/g, '_')}`;

    if (isStartNode(node)) {
      functions.push(generateStartNodeFunction(node, functionName));
    } else if (isAgentNode(node)) {
      functions.push(generateAgentNodeFunction(node, functionName));
    } else if (isCodeNode(node)) {
      functions.push(generateCodeNodeFunction(node, functionName));
    } else if (isLLMNode(node)) {
      functions.push(generateLLMNodeFunction(node, functionName));
    } else if (isIfElseNode(node)) {
      functions.push(generateIfElseNodeFunction(node, functionName));
    } else if (isAnswerNode(node)) {
      functions.push(generateAnswerNodeFunction(node, functionName));
    } else if (isVariableAssignmentNode(node)) {
      functions.push(generateVariableAssignmentNodeFunction(node, functionName));
    } else {
      functions.push(generateGenericNodeFunction(node, functionName));
    }
  }

  return functions.join('\n\n');
}

function generateStartNodeFunction(node: WorkflowNode, functionName: string): string {
  const data = node.data as any;
  const variables = data.variables || [];

  let variableValidation = '';
  for (const variable of variables) {
    if (variable.required) {
      variableValidation += `    [[ -z "\${workflow_vars["${variable.variable}"]:-}" ]] && {
        log_error "${variable.variable} is required"
        show_usage
        exit 1
    }
`;
    }
  }

  return `# Execute start node: ${node.id}
${functionName}() {
    log_step "Starting workflow: ${data.title || node.id}"
    
    # Validate required variables
${variableValidation}    
    log_success "Workflow initialized successfully"
    set_workflow_state "current_node" "${node.id}"
}`;
}

function generateAgentNodeFunction(node: WorkflowNode, functionName: string): string {
  const data = node.data as any;

  return `# Execute agent node: ${node.id}
${functionName}() {
    log_step "🤖 Running Agent: ${data.title || node.id}"
    
    local agent_exit_code=0
    local command="${data.command || 'opencode'}"
    
    # Resolve and render template if provided
    local prompt=""
    if [[ -n "${data.prompt_template?.template_id || ''}" ]]; then
        local template_content
        if ! template_content=\$(resolve_template "${data.prompt_template?.template_id || ''}" "${data.prompt_template?.source || 'library'}"); then
            log_error "Failed to resolve template '${data.prompt_template?.template_id || ''}'"
            return 1
        fi
        
        if ! prompt=\$(render_template "\$template_content" "\$(get_workflow_var 'task_description' '')"); then
            log_error "Failed to render template"
            return 1
        fi
    else
        prompt="\$(get_workflow_var 'task_description' 'Default task')"
    fi
    
    log_debug "Generated prompt length: \${#prompt} characters"
    
    # Execute agent command with proper error handling
    if [[ "\$USE_MOCK_TOOLS" == "true" ]]; then
        log_debug "Using mock \$command"
        mock_opencode "\$prompt" || agent_exit_code=\$?
    elif command -v "\$command" >/dev/null 2>&1; then
        log_debug "Using real \$command with timeout \${AGENT_TIMEOUT}s"
        ${data.working_directory ? `cd "${data.working_directory}"` : ''}
        timeout "\$AGENT_TIMEOUT" "\$command" ${(data.args || []).map((arg: any) => `"${arg}"`).join(' ')} "\$prompt" || agent_exit_code=\$?
        
        # Handle timeout gracefully
        if [[ \$agent_exit_code -eq 124 ]]; then
            log_error "\$command timed out after \${AGENT_TIMEOUT}s, falling back to mock"
            mock_opencode "\$prompt" || agent_exit_code=\$?
        fi
    else
        log_info "\$command not found, falling back to mock"
        mock_opencode "\$prompt" || agent_exit_code=\$?
    fi
    
    if [[ \$agent_exit_code -ne 0 ]]; then
        handle_error \$agent_exit_code "Agent execution" "${node.id}"
        return \$agent_exit_code
    fi
    
    log_success "Agent completed successfully"
    set_workflow_state "current_node" "${node.id}"
}`;
}

function generateCodeNodeFunction(node: WorkflowNode, functionName: string): string {
  const data = node.data as any;

  return `# Execute code node: ${node.id}
${functionName}() {
    log_step "🔧 Running Code: ${data.title || node.id}"
    
    local exit_code=0
    local command="${data.command}"
    
    # Change to working directory if specified
    ${
      data.working_directory
        ? `
    local original_dir
    original_dir=\$(pwd)
    
    if ! cd "${data.working_directory}"; then
        log_error "Failed to change to directory: ${data.working_directory}"
        return 1
    fi
    
    log_debug "Changed to directory: \$(pwd)"`
        : ''
    }
    
    # Execute command with fallback options
    if [[ "\$USE_MOCK_TOOLS" == "true" ]]; then
        log_debug "Using mock command"
        mock_command "\$command" ${(data.args || []).map((arg: any) => `"${arg}"`).join(' ')} || exit_code=\$?
    else
        log_debug "Using real command: \$command"
        "\$command" ${(data.args || []).map((arg: any) => `"${arg}"`).join(' ')} || exit_code=\$?
    fi
    
    ${
      data.working_directory
        ? `
    # Return to original directory
    cd "\$original_dir" || {
        log_error "Failed to return to original directory"
        return 1
    }`
        : ''
    }
    
    # Handle success/failure routing
    if [[ \$exit_code -eq 0 ]]; then
        log_success "Code execution completed successfully"
        ${data.on_success ? `execute_node_${data.on_success.replace(/[^a-zA-Z0-9]/g, '_')}` : ''}
    else
        log_error "Code execution failed with exit code: \$exit_code"
        ${data.on_failure ? `execute_node_${data.on_failure.replace(/[^a-zA-Z0-9]/g, '_')}` : `return \$exit_code`}
    fi
    
    set_workflow_state "current_node" "${node.id}"
}`;
}

