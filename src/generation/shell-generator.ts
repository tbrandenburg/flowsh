/**
 * Generates the script header with metadata and basic setup
 */
function generateScriptHeader(workflow: FlowshWorkflow, options: GenerationOptions): string {
  const workflowName = workflow.workflow?.name || workflow.metadata?.name || 'Unnamed Workflow';
  const workflowVersion = workflow.workflow?.version || workflow.metadata?.version || '1.0.0';
  const description = workflow.workflow?.description || workflow.metadata?.description || '';

  return `#!/bin/${options.shell || 'bash'}
# Generated by flowsh v1.0.0
# Source: ${workflowName}
${description ? `# Description: ${description}` : ''}
# Version: ${workflowVersion}
# Generated: ${new Date().toISOString()}

set -euo pipefail

# =============================================================================
# WORKFLOW CONFIGURATION
# =============================================================================

# Workflow variables
declare -A workflow_vars
declare -A workflow_state

# Control flags for testing and configuration
USE_MOCK_TOOLS=\${USE_MOCK_TOOLS:-true}
AGENT_TIMEOUT=\${AGENT_TIMEOUT:-${options.defaultTimeout || 60}}
VERBOSE=\${VERBOSE:-${options.verbose ? 'true' : 'false'}}
WORKFLOW_NAME="${workflowName}"
WORKFLOW_VERSION="${workflowVersion}"

# Color codes for output
RED='\\033[0;31m'
GREEN='\\033[0;32m'
YELLOW='\\033[1;33m'
BLUE='\\033[0;34m'
CYAN='\\033[0;36m'
NC='\\033[0m' # No Color`;
}

/**
 * Generates utility functions for logging, error handling, etc.
 */
function generateUtilityFunctions(): string {
  return `# =============================================================================
# UTILITY FUNCTIONS
# =============================================================================

# Logging functions with colors
log_info() {
    echo -e "\${CYAN}ℹ️  \$*\${NC}"
}

log_success() {
    echo -e "\${GREEN}✅ \$*\${NC}"
}

log_error() {
    echo -e "\${RED}❌ \$*\${NC}" >&2
}

log_warning() {
    echo -e "\${YELLOW}⚠️  \$*\${NC}" >&2
}

log_debug() {
    [[ "\$VERBOSE" == "true" ]] && echo -e "\${BLUE}🔍 DEBUG: \$*\${NC}" >&2 || true
}

log_step() {
    echo -e "\${CYAN}🚀 \$*\${NC}"
}

# Enhanced error handling
handle_error() {
    local exit_code=\$1
    local context="\$2"
    local node_id="\${3:-unknown}"
    
    case \$exit_code in
        124)
            log_error "Timeout: \$context took longer than \${AGENT_TIMEOUT}s (node: \$node_id)"
            ;;
        127)
            log_error "Command not found in: \$context (node: \$node_id)"
            ;;
        1)
            log_error "General error in: \$context (node: \$node_id)"
            ;;
        *)
            log_error "Unknown error (exit code \$exit_code) in: \$context (node: \$node_id)"
            ;;
    esac
    
    return \$exit_code
}

# Variable management
set_workflow_var() {
    local var_name="\$1"
    local var_value="\$2"
    workflow_vars["\$var_name"]="\$var_value"
    log_debug "Set variable: \$var_name = \$var_value"
}

get_workflow_var() {
    local var_name="\$1"
    local default_value="\${2:-}"
    echo "\${workflow_vars[\$var_name]:-\$default_value}"
}

# State management
set_workflow_state() {
    local state_key="\$1"
    local state_value="\$2"
    workflow_state["\$state_key"]="\$state_value"
    log_debug "Set state: \$state_key = \$state_value"
}

get_workflow_state() {
    local state_key="\$1"
    local default_value="\${2:-}"
    echo "\${workflow_state[\$state_key]:-\$default_value}"
}

# Variable substitution in templates
substitute_variables() {
    local template="\$1"
    local result="\$template"
    
    # Find all variable references in the format {{#variable_name#}}
    while [[ \$result =~ \\{\\{#([^#]+)#\\}\\} ]]; do
        local var_ref="\${BASH_REMATCH[1]}"
        local var_value=\$(get_workflow_var "\$var_ref" "")
        
        if [[ -z "\$var_value" ]]; then
            log_warning "Variable reference '\$var_ref' not found, using empty string"
        fi
        
        # Escape special characters for sed
        local escaped_value=\$(printf '%s\\n' "\$var_value" | sed 's/[[\\.\\*^\\$()+?{|]/\\\\&/g')
        result=\$(echo "\$result" | sed "s|{{#\${var_ref}#}}|\$escaped_value|g")
    done
    
    echo "\$result"
}`;
}

