/**
 * Generates the main execution flow
 */
function generateMainFlow(nodes: WorkflowNode[], edges: WorkflowEdge[]): string {
  // Find start node
  const startNodes = nodes.filter(isStartNode);
  const startNodeId = startNodes.length > 0 ? startNodes[0]!.id : nodes[0]?.id;

  // Build execution order (simplified linear execution for now)
  let executionOrder = '';
  if (startNodeId) {
    executionOrder = `    execute_node_${startNodeId.replace(/[^a-zA-Z0-9]/g, '_')}\n`;

    // Add other nodes in order (simplified approach)
    const remainingNodes = nodes.filter(
      node => node.id !== startNodeId && !isEndNode(node) && !isAnswerNode(node)
    );
    for (const node of remainingNodes) {
      executionOrder += `    execute_node_${node.id.replace(/[^a-zA-Z0-9]/g, '_')}\n`;
    }

    // Add end/answer nodes last
    const endNodes = nodes.filter(node => isEndNode(node) || isAnswerNode(node));
    for (const node of endNodes) {
      executionOrder += `    execute_node_${node.id.replace(/[^a-zA-Z0-9]/g, '_')}\n`;
    }
  }

  return `# =============================================================================
# MAIN EXECUTION FLOW
# =============================================================================

# Execute the workflow
execute_workflow() {
    log_info "Starting workflow execution: \$WORKFLOW_NAME"
    log_info "Nodes: ${nodes.length}, Edges: ${edges.length}"
    
${executionOrder}
    
    local completion_status=\$(get_workflow_state "completed" "false")
    if [[ "\$completion_status" == "true" ]]; then
        log_success "Workflow completed successfully"
    else
        log_warning "Workflow execution finished but completion status unclear"
    fi
}`;
}

/**
 * Generates argument parsing logic
 */
function generateArgumentParsing(workflow: FlowshWorkflow): string {
  const envVars = workflow.environment_variables || workflow.spec?.environment_variables || [];

  let argumentHandling = '';
  let usageText = '';

  for (let i = 0; i < envVars.length; i++) {
    const envVar = envVars[i];
    if (envVar) {
      argumentHandling += `    workflow_vars["${envVar.variable}"]="\${${i + 1}:-}"\n`;
      usageText += `  arg${i + 1}    ${envVar.name || envVar.variable}${envVar.description ? ` - ${envVar.description}` : ''}\n`;
    }
  }

  return `# =============================================================================
# ARGUMENT PARSING AND INITIALIZATION
# =============================================================================

# Usage help
show_usage() {
    cat <<EOF
\$WORKFLOW_NAME v\$WORKFLOW_VERSION

Usage: \$0 [OPTIONS] ${envVars.map((_, i) => `<arg${i + 1}>`).join(' ')}

Arguments:
${usageText}Options:
  --no-mock         Use real tools instead of mocks
  --timeout SECS    Set agent timeout in seconds (default: \$AGENT_TIMEOUT)
  --verbose         Enable verbose debug output
  --help            Show this help message

Environment Variables:
  USE_MOCK_TOOLS    Set to 'false' to use real tools (default: true)
  AGENT_TIMEOUT     Agent timeout in seconds (default: 60)
  VERBOSE           Set to 'true' for debug output (default: false)

Examples:
  \$0 "Implement user auth" /path/to/project
  \$0 --no-mock --verbose "Fix bug in API" /path/to/project
EOF
}

# Initialize workflow with arguments
init_workflow() {
${argumentHandling}
    
    # Validate required arguments
    ${envVars
      .map(
        (envVar, i) =>
          `[[ -z "\${workflow_vars["${envVar?.variable || `arg${i}`}"]}" ]] && {
        log_error "${envVar?.variable || `arg${i}`} is required"
        show_usage
        exit 1
    }`
      )
      .join('\n    ')}
    
    log_success "Workflow initialized with provided arguments"
    ${envVars
      .map(
        envVar =>
          `log_debug "${envVar?.variable || 'unknown'}: \${workflow_vars["${envVar?.variable || 'unknown'}"]}"`
      )
      .join('\n    ')}
}

# Parse command line arguments
while [[ \$# -gt 0 ]]; do
    case \$1 in
        --no-mock)
            USE_MOCK_TOOLS=false
            shift
            ;;
        --timeout)
            [[ -n "\${2:-}" ]] || {
                log_error "--timeout requires a value"
                exit 1
            }
            [[ "\$2" =~ ^[0-9]+\$ ]] || {
                log_error "Timeout must be a positive integer"
                exit 1
            }
            AGENT_TIMEOUT="\$2"
            shift 2
            ;;
        --verbose)
            VERBOSE=true
            shift
            ;;
        --help)
            show_usage
            exit 0
            ;;
        -*)
            log_error "Unknown option: \$1"
            show_usage >&2
            exit 1
            ;;
        *)
            break
            ;;
    esac
done`;
}

